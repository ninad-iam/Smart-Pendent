#!/usr/bin/env python3
"""
Turns the 4x3 emoji sheet into an RGB565 C header for the Waveshare 1.85" round LCD.

  python3 convert_emojis.py sheet.png            # default 300x300 per emoji
  python3 convert_emojis.py sheet.png --size 240 # smaller = less flash
  python3 convert_emojis.py sheet.png --swap     # byte-swap if colours look wrong

Outputs: emoji_data.h and preview.png (what the display will show).
"""
import argparse
import numpy as np
from PIL import Image, ImageFilter
from scipy import ndimage as ndi

NAMES = [['happy', 'joy',     'wink',    'sad'],
         ['surprised', 'dizzy', 'worried', 'love'],
         ['angry', 'silly',   'excited', 'sick']]
# grid centres of the emojis in the 1024x1024 sheet
COLS = [162, 394, 625, 857]
ROWS = [280, 512, 745]
# emojis that have extra bits (tears / hearts / vomit) hanging off the face
EXTRAS = {'joy': 'blue', 'worried': 'blue', 'love': 'red', 'sick': 'green'}
H, R = 112, 79          # half-crop size, face radius in source pixels

BAYER = np.array([[0, 8, 2, 10], [12, 4, 14, 6],
                  [3, 11, 1, 9], [15, 7, 13, 5]]) / 16.0 - 0.5


def hue_deg(a):
    r, g, b = a[..., 0], a[..., 1], a[..., 2]
    mx, mn = a.max(2), a.min(2)
    d = np.maximum(mx - mn, 1e-6)
    return np.where(mx == r, ((g - b) / d) % 6,
                    np.where(mx == g, (b - r) / d + 2, (r - g) / d + 4)) * 60


def extract(im):
    """Cut every emoji out of the sheet (shadow removed) onto black."""
    a = np.array(im).astype(float)
    mx, mn = a.max(2), a.min(2)
    sat = (mx - mn) / np.maximum(mx, 1)
    mask = ndi.binary_fill_holes(ndi.binary_closing(sat > 0.10, iterations=2))
    mask = ndi.binary_opening(mask, iterations=2)
    hue = hue_deg(a)
    yy, xx = np.mgrid[0:im.height, 0:im.width]
    out = {}
    for ri, cy in enumerate(ROWS):
        for ci, cx in enumerate(COLS):
            n = NAMES[ri][ci]
            body = ((xx - cx) ** 2 + (yy - cy) ** 2) <= R * R
            m = mask & body                       # face only -> drops the drop-shadow
            ex = EXTRAS.get(n)
            if ex == 'red':
                m |= ndi.binary_fill_holes(mask & ~body & (yy < cy - 10)) & ~body
            elif ex:
                sel = ((hue > 170) & (hue < 260) & (sat > 0.25)) if ex == 'blue' \
                    else ((hue > 75) & (hue < 170) & (sat > 0.35))
                sel = ndi.binary_opening(sel & mask & ~body)
                m |= ndi.binary_dilation(sel, iterations=2) & mask & ~body
            m = ndi.binary_erosion(m[cy-H:cy+H, cx-H:cx+H])
            al = Image.fromarray((m * 255).astype('uint8')).filter(ImageFilter.GaussianBlur(0.8))
            crop = im.crop((cx-H, cy-H, cx+H, cy+H))
            img = Image.new('RGB', crop.size, (0, 0, 0))
            img.paste(crop, (0, 0), al)
            out[n] = img
    return out


def fit_to_canvas(img, size, scale):
    """Centre the emoji's bounding box on a size x size black canvas."""
    g = np.array(img.convert('L')) > 12
    ys, xs = np.nonzero(g)
    box = img.crop((xs.min(), ys.min(), xs.max() + 1, ys.max() + 1))
    w, h = box.size
    box = box.resize((round(w * scale), round(h * scale)), Image.LANCZOS)
    canvas = Image.new('RGB', (size, size), (0, 0, 0))
    canvas.paste(box, ((size - box.width) // 2, (size - box.height) // 2))
    return canvas


def to_rgb565(img, swap):
    a = np.array(img).astype(float)
    a += BAYER[np.arange(a.shape[0])[:, None] % 4, np.arange(a.shape[1])[None, :] % 4][..., None] * 6
    a = np.clip(a, 0, 255).astype(np.uint16)
    v = ((a[..., 0] & 0xF8) << 8) | ((a[..., 1] & 0xFC) << 3) | (a[..., 2] >> 3)
    if swap:
        v = ((v & 0xFF) << 8) | (v >> 8)
    return v.astype(np.uint16)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('src')
    ap.add_argument('--size', type=int, default=300)
    ap.add_argument('--swap', action='store_true')
    args = ap.parse_args()

    faces = extract(Image.open(args.src).convert('RGB'))
    # one global scale so every emoji has the same face size, and the widest one
    # (hearts / vomit) still fits inside the round screen
    max_r = 0
    for img in faces.values():
        g = np.array(img.convert('L')) > 12
        ys, xs = np.nonzero(g)
        cx, cy = (xs.min() + xs.max()) / 2, (ys.min() + ys.max()) / 2
        max_r = max(max_r, np.hypot(xs - cx, ys - cy).max())
    scale = (args.size / 2 - 2) / max_r
    print(f'scale {scale:.2f}x, face diameter ~{2*R*scale:.0f}px')

    order = [n for row in NAMES for n in row]
    prev = Image.new('RGB', (360 * 4, 360 * 3))
    with open('emoji_data.h', 'w') as f:
        f.write('// Auto-generated by convert_emojis.py - do not edit\n#pragma once\n#include <Arduino.h>\n\n')
        f.write(f'#define EMOJI_SIZE {args.size}\n#define EMOJI_COUNT {len(order)}\n\n')
        f.write('enum EmojiId {\n' + ''.join(f'  EMOJI_{n.upper()},\n' for n in order) + '};\n\n')
        for i, n in enumerate(order):
            canvas = fit_to_canvas(faces[n], args.size, scale)
            px = to_rgb565(canvas, args.swap).flatten()
            f.write(f'const uint16_t emoji_{n}[EMOJI_SIZE * EMOJI_SIZE] PROGMEM = {{\n')
            for k in range(0, len(px), 24):
                f.write(','.join(f'0x{v:04X}' for v in px[k:k+24]) + ',\n')
            f.write('};\n\n')
            disc = Image.new('RGB', (360, 360))
            disc.paste(canvas, ((360 - args.size) // 2, (360 - args.size) // 2))
            mask = Image.new('L', (360, 360), 0)
            from PIL import ImageDraw
            ImageDraw.Draw(mask).ellipse((0, 0, 359, 359), fill=255)   # round bezel
            black = Image.new('RGB', (360, 360))
            prev.paste(Image.composite(disc, black, mask), ((i % 4) * 360, (i // 4) * 360))
        f.write('const uint16_t* const EMOJI_TABLE[EMOJI_COUNT] = {\n')
        f.write(''.join(f'  emoji_{n},\n' for n in order) + '};\n')
    prev.resize((prev.width // 2, prev.height // 2)).save('preview.png')
    print(f'wrote emoji_data.h ({args.size*args.size*2*len(order)/1e6:.2f} MB of flash) and preview.png')


if __name__ == '__main__':
    main()
